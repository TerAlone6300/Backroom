#!/bin/sh
# Regenerates vk_shaders.h: frame.vert (full-screen triangle) and the scene shader, which is shared with OpenGL ES (app/src/main/assets/shaders/scene.glsl). Needs glslangValidator (apt install glslang-tools).
# The generated header is committed, so the Android build does not need glslang.
set -e
cd "$(dirname "$0")"
OUT=../vk_shaders.h
TMP=$(mktemp -d)
glslangValidator -V --vn kVertSpv -o "$TMP/v.h" frame.vert
(printf '#version 450\n'; cat ../../assets/shaders/scene.glsl) > "$TMP/scene.frag"
glslangValidator -V --vn kFragSpv -o "$TMP/f.h" "$TMP/scene.frag"
{
  echo "// Generated by shaders/compile_shaders.sh from shaders/frame.vert and frame.frag. Do not edit by hand."
  echo "#pragma once"
  echo "#include <cstdint>"
  sed -e '/^[[:space:]]*\/\/ /d' -e '/#pragma once/d' -e 's/^const uint32_t/static const uint32_t/' "$TMP/v.h"
  sed -e '/^[[:space:]]*\/\/ /d' -e '/#pragma once/d' -e 's/^const uint32_t/static const uint32_t/' "$TMP/f.h"
} > "$OUT"
rm -rf "$TMP"
echo "wrote $OUT"
